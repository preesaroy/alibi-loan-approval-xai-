def find_dataset():
    """Find the Kaggle CSV in common Colab upload locations."""
    candidates = [
        DATA_DIR / "loan_approval_dataset.csv",
        Path("loan_approval_dataset.csv"),
        Path("/content/loan_approval_dataset.csv"),
        Path("/content/data/loan_approval_dataset.csv"),
    ]
    for path in candidates:
        if path.exists():
            return path
    # Fall back to any CSV with a likely loan-approval filename.
    for base in [Path.cwd(), Path("/content")]:
        if base.exists():
            for path in base.glob("**/*.csv"):
                if "loan" in path.name.lower() and "approval" in path.name.lower():
                    return path
    raise FileNotFoundError(
        "Dataset CSV not found. Download loan_approval_dataset.csv from Kaggle "
        "and place it in data/loan_approval_dataset.csv. See README.md."
    )


def normalize_columns(df):
    """Normalize common Kaggle column-name whitespace and casing."""
    df = df.copy()
    df.columns = [
        re.sub(r"[^a-z0-9]+", "_", str(c).strip().lower()).strip("_")
        for c in df.columns
    ]
    return df


def load_data():
    path = find_dataset()
    print(f"Loading dataset: {path}")
    df = pd.read_csv(path)

# Display dataset dimensions
    print("\n========== DATASET OVERVIEW ==========")

    rows, columns = df.shape
    print(f"Number of rows: {rows}")
    print(f"Number of columns: {columns}")


    df = normalize_columns(df)

    # Kaggle file often contains whitespace in column names, normalized above.
    target_candidates = ["loan_status", "loanstatus", "loan_approval_status"]
    target = next((c for c in target_candidates if c in df.columns), None)
    if target is None:
        raise ValueError(
            f"Could not find target column. Columns found: {list(df.columns)}. "
            "Expected loan_status (Approved/Rejected)."
        )

    # Drop duplicate rows, but keep the original target column until mapped.
    df = df.drop_duplicates().reset_index(drop=True)
    y_raw = df.pop(target)

    # Target variants found in common versions of this Kaggle dataset:
    # Approved/Rejected; Y/N; 1/0.
    if pd.api.types.is_numeric_dtype(y_raw):
        y = y_raw.astype(int)
        unique = set(y.dropna().unique())
        if not unique.issubset({0, 1}):
            raise ValueError(f"Unexpected numeric target labels: {unique}")
    else:
        mapping = {
            "approved": 1, "approve": 1, "yes": 1, "y": 1, "1": 1,
            "rejected": 0, "reject": 0, "no": 0, "n": 0, "0": 0
        }
        normalized = y_raw.astype(str).str.strip().str.lower()
        y = normalized.map(mapping)
        if y.isna().any():
            raise ValueError(
                "Unrecognized target labels: "
                + str(sorted(normalized[y.isna()].unique()))
            )
        y = y.astype(int)

    X = df.copy()

    # Remove identifier-like columns, which should not drive predictions.
    id_cols = [c for c in X.columns if c in {"loan_id", "id", "applicant_id"}]
    X = X.drop(columns=id_cols, errors="ignore")

    # Convert common yes/no or graduate strings consistently; other categories stay categorical.
    for col in X.select_dtypes(include=["object"]).columns:
        X[col] = X[col].astype(str).str.strip()
        X[col] = X[col].replace({"nan": np.nan, "None": np.nan, "": np.nan})

    return X, y, path


def build_model(X_train, y_train):
    categorical = X_train.select_dtypes(include=["object", "category", "bool"]).columns.tolist()
    numeric = [c for c in X_train.columns if c not in categorical]

    preprocessor = ColumnTransformer(
        transformers=[
            ("num", Pipeline([
                ("imputer", SimpleImputer(strategy="median")),
                ("scaler", StandardScaler())
            ]), numeric),
            ("cat", Pipeline([
                ("imputer", SimpleImputer(strategy="most_frequent")),
                ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False))
            ]), categorical)
        ],
        remainder="drop",
        verbose_feature_names_out=False
    )

    model = Pipeline([
        ("prep", preprocessor),
        ("clf", RandomForestClassifier(
            n_estimators=300,
            min_samples_leaf=2,
            class_weight="balanced_subsample",
            random_state=RANDOM_STATE,
            n_jobs=-1
        ))
    ])
    model.fit(X_train, y_train)
    return model


def evaluate(model, X_test, y_test):
    pred = model.predict(X_test)
    prob = model.predict_proba(X_test)[:, 1]
    metrics = {
        "accuracy": accuracy_score(y_test, pred),
        "precision_approved": precision_score(y_test, pred, pos_label=1, zero_division=0),
        "recall_approved": recall_score(y_test, pred, pos_label=1, zero_division=0),
        "f1_approved": f1_score(y_test, pred, pos_label=1, zero_division=0),
        "roc_auc": roc_auc_score(y_test, prob)
    }
    print("\\n=== Held-out test metrics ===")
    for k, v in metrics.items():
        print(f"{k:22s}: {v:.4f}")
    print("\\nClassification report:")
    print(classification_report(
        y_test, pred, labels=[0, 1],
        target_names=["Rejected", "Approved"], zero_division=0
    ))

    cm = confusion_matrix(y_test, pred, labels=[0, 1])
    fig, ax = plt.subplots(figsize=(5.5, 4.5))
    im = ax.imshow(cm, cmap="Blues")
    ax.set_title("Loan approval — confusion matrix")
    ax.set_xlabel("Predicted")
    ax.set_ylabel("Actual")
    ax.set_xticks([0, 1], ["Rejected", "Approved"])
    ax.set_yticks([0, 1], ["Rejected", "Approved"])
    for (i, j), value in np.ndenumerate(cm):
        ax.text(j, i, str(value), ha="center", va="center", fontsize=12)
    fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    fig.tight_layout()
    fig.savefig(ARTIFACT_DIR / "confusion_matrix.png", dpi=180)
    show_plot(fig)

    pd.DataFrame([metrics]).to_csv(ARTIFACT_DIR / "test_metrics.csv", index=False)
    return metrics


def explain_with_alibi_anchor(model, X_train, X_test):
    """Generate an Alibi AnchorTabular explanation for one held-out application."""
    try:
        from alibi.explainers import AnchorTabular
    except ImportError as exc:
        raise RuntimeError("Alibi is not installed. Run: pip install alibi") from exc

    preprocessor = model.named_steps["prep"]
    classifier = model.named_steps["clf"]
    train_transformed = preprocessor.transform(X_train)
    test_transformed = preprocessor.transform(X_test)
    transformed_names = preprocessor.get_feature_names_out().tolist()

    predict_fn = lambda arr: classifier.predict(np.asarray(arr))
    explainer = AnchorTabular(predict_fn, feature_names=transformed_names)
    explainer.fit(train_transformed, disc_perc=(25, 50, 75))

    idx = 0
    exp = explainer.explain(test_transformed[idx], threshold=0.90)
    prediction = int(model.predict(X_test.iloc[[idx]])[0])
    probability = float(model.predict_proba(X_test.iloc[[idx]])[0, 1])

    print("\\n=== Alibi AnchorTabular explanation ===")
    print("Applicant index in held-out set:", idx)
    print("Predicted label:", "Approved" if prediction == 1 else "Rejected")
    print(f"Predicted approval probability: {probability:.3f}")
    print("Anchor rule:", exp.data.get("anchor", []))
    print("Anchor precision:", exp.data.get("precision"))
    print("Anchor coverage:", exp.data.get("coverage"))
    return exp


def constrained_counterfactual_search(
    model, X_train, x, target_class,
    immutable_features=("education",),
    max_candidates=10000
):
    """
    Transparent counterfactual baseline:
    find the nearest observed training applicant predicted as target_class.
    Selected immutable features are held fixed. This is not Alibi's built-in
    CounterfactualRLTabular algorithm and does not establish causality.
    """
    candidates = X_train.iloc[:max_candidates].copy()
    candidates = candidates.loc[model.predict(candidates) == target_class]

    for col in immutable_features:
        if col in x.index and col in candidates.columns:
            candidates = candidates[candidates[col].astype(str) == str(x[col])]

    if candidates.empty:
        print("\\nNo candidate found under the current target and constraints.")
        return None

    categorical = X_train.select_dtypes(include=["object", "category", "bool"]).columns.tolist()
    numeric = [c for c in X_train.columns if c not in categorical]
    spans = {}
    for c in numeric:
        span = float(pd.to_numeric(X_train[c], errors="coerce").max() -
                     pd.to_numeric(X_train[c], errors="coerce").min())
        spans[c] = span if span > 0 else 1.0

    distances, change_counts = [], []
    for _, row in candidates.iterrows():
        diffs = []
        for c in numeric:
            diffs.append(abs(float(row[c]) - float(x[c])) / spans[c])
        for c in categorical:
            diffs.append(0.0 if str(row[c]) == str(x[c]) else 1.0)
        distances.append(float(np.mean(diffs)))
        change_counts.append(sum(str(row[c]) != str(x[c]) for c in X_train.columns))

    score = np.asarray(distances) + 0.03 * np.asarray(change_counts)
    cf = candidates.iloc[int(np.argmin(score))]
    original_label = int(model.predict(pd.DataFrame([x]))[0])
    cf_label = int(model.predict(pd.DataFrame([cf]))[0])

    comparison = pd.DataFrame({
        "feature": X_train.columns,
        "original": [x[c] for c in X_train.columns],
        "counterfactual_candidate": [cf[c] for c in X_train.columns],
        "changed": [str(x[c]) != str(cf[c]) for c in X_train.columns]
    })
    comparison = comparison[comparison["changed"]]
    print("\\n=== Counterfactual candidate (nearest observed example) ===")
    print("Original prediction:", "Approved" if original_label else "Rejected")
    print("Candidate prediction:", "Approved" if cf_label else "Rejected")
    print(comparison.to_string(index=False) if not comparison.empty else "No features changed.")
    comparison.to_csv(ARTIFACT_DIR / "counterfactual_changes.csv", index=False)
    return cf


def global_importance(model, X_test, y_test):
    result = permutation_importance(
        model, X_test, y_test, n_repeats=5, random_state=RANDOM_STATE,
        scoring="f1", n_jobs=-1
    )
    importance = pd.Series(result.importances_mean, index=X_test.columns).sort_values(ascending=False)
    print("\\n=== Permutation importance ===")
    print(importance.head(12).to_string())
    importance.rename("importance").to_csv(ARTIFACT_DIR / "permutation_importance.csv")
    ax = importance.head(12).sort_values().plot(
        kind="barh", figsize=(7, 5), title="Top permutation importances"
    )
    ax.set_xlabel("Mean decrease in F1 after shuffling")
    plt.tight_layout()
    plt.savefig(ARTIFACT_DIR / "permutation_importance.png", dpi=180)
    fig = plt.gcf()
    show_plot(fig)
    return importance


def main():
    X, y, data_path = load_data()
    print("Dataset:", data_path)
    print("Rows / input features:", X.shape)
    print("Target counts (0=rejected, 1=approved):")
    print(y.value_counts().sort_index().rename(index={0: "Rejected", 1: "Approved"}))
    print("Target proportions:")
    print(y.value_counts(normalize=True).sort_index().rename(index={0: "Rejected", 1: "Approved"}))

    # Graph 1: show the label balance before training.
    plot_target_distribution(y)

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, stratify=y, random_state=RANDOM_STATE
    )
    model = build_model(X_train, y_train)

    # Graph 2: confusion matrix is displayed inside evaluate().
    metrics = evaluate(model, X_test, y_test)

    # Graph 3: compact chart of test-set metrics.
    plot_evaluation_metrics(metrics)

    # Graph 4: probabilities for the first 25 held-out applicants.
    plot_approval_probabilities(model, X_test, y_test)

    # Graph 5: global feature importance.
    global_importance(model, X_test, y_test)

    try:
        explain_with_alibi_anchor(model, X_train, X_test)
    except Exception as exc:
        print("\\nAlibi AnchorTabular did not run:", repr(exc))
        print("See README troubleshooting; model evaluation and plots may still have completed.")

    predictions = model.predict(X_test)
    rejected_indices = np.flatnonzero(predictions == 0)
    approved_indices = np.flatnonzero(predictions == 1)
    if len(rejected_indices) and len(approved_indices):
        x = X_test.iloc[int(rejected_indices[0])]
        print("\\nSelected held-out applicant:")
        print(x.to_string())
        constrained_counterfactual_search(model, X_train, x, target_class=1)
    else:
        print("Could not find both predicted classes in this test split.")

    print(f"\\nArtifacts saved in: {ARTIFACT_DIR.resolve()}")
    print("Educational prototype only — never use this model to make real lending decisions.")


if __name__ == "__main__":
    main()